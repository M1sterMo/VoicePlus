@Composable
fun voiceColorScheme(
  color: ThemeColor,
  dark: Boolean,
): ColorScheme {
  if (color == ThemeColor.DYNAMIC && Build.VERSION.SDK_INT >= 31) {
    val context = LocalContext.current
    return if (dark) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
  }
  return when (color) {
    ThemeColor.DYNAMIC -> if (dark) darkColorScheme() else lightColorScheme()
    ThemeColor.TEAL -> if (dark) TealDark else TealLight
    ThemeColor.GREEN -> if (dark) GreenDark else GreenLight
    ThemeColor.ORANGE -> if (dark) OrangeDark else OrangeLight
    ThemeColor.ROSE -> if (dark) RoseDark else RoseLight
    ThemeColor.BLUE -> if (dark) BlueDark else BlueLight
  }
}

